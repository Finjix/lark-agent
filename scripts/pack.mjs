import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
execFileSync(process.execPath,[path.join(root,'scripts','licenses.mjs')],{stdio:'inherit',windowsHide:true});
const release=path.join(root,'releases'),stage=path.join(release,'lark-desktop-agent-win-x64');
await fs.mkdir(release,{recursive:true});
if(await fs.stat(stage).then(()=>true,()=>false))throw Error('已有暂存包，请先另存旧包并移走暂存目录后重新打包');
await fs.mkdir(stage);
const entries=['src','tests','scripts','docs','dist','node_modules','package.json','package-lock.json','tsconfig.json','.env.example','README.md','start.cmd','doctor.cmd','project.cmd'];
for(const name of entries)await fs.cp(path.join(root,name),path.join(stage,name),{recursive:true});
await fs.mkdir(path.join(stage,'runtime'));await fs.cp(path.join(root,'runtime','node'),path.join(stage,'runtime','node'),{recursive:true});
const manifest={version:'1.0.0',platform:'win32-x64',node:'24.21.0',desktop:['26.1007.9446.0'],createdAt:new Date().toISOString(),files:{}};
async function walk(dir){for(const item of await fs.readdir(dir,{withFileTypes:true})){const file=path.join(dir,item.name);if(item.isDirectory())await walk(file);else if(item.isFile())manifest.files[path.relative(stage,file).replaceAll('\\','/')]=createHash('sha256').update(await fs.readFile(file)).digest('hex');else throw Error('包中不能包含符号链接');}}
await walk(stage);await fs.writeFile(path.join(stage,'manifest.json'),JSON.stringify(manifest,null,2));
const zip=path.join(release,'lark-desktop-agent-win-x64.zip');
execFileSync('tar.exe',['-a','-c','-f',zip,'-C',release,path.basename(stage)],{windowsHide:true,stdio:'inherit'});
const sha=createHash('sha256').update(await fs.readFile(zip)).digest('hex');await fs.writeFile(zip+'.sha256',`${sha}  ${path.basename(zip)}\n`);
console.log(JSON.stringify({archive:zip,sha256:sha,files:Object.keys(manifest.files).length}));
